/* 视觉 x/y → 缓冲：相位 wrap */
static UINT32 MapFramebufferX(UINT32 VisualX) {
    return (VisualX + BOARD_FRAMEBUFFER_PHASE_X) % BOARD_FRAMEBUFFER_WIDTH;
}

static UINT32 MapFramebufferY(UINT32 VisualY) {
    return (VisualY + BOARD_FRAMEBUFFER_PHASE_Y) % BOARD_FRAMEBUFFER_HEIGHT;
}

static volatile UINT32 *PixelAt(UINT64 SplashBase, UINT32 X, UINT32 Y) {
    UINT8 *Base = (UINT8 *)(UINTN)SplashBase;
    UINT32 BufferX = MapFramebufferX(X);
    UINT32 BufferY = MapFramebufferY(Y);

    return (volatile UINT32 *)(Base + (UINTN)BufferY * BOARD_FRAMEBUFFER_STRIDE_BYTES +
                               (UINTN)BufferX * 4u);
}

static void FillRectangle(UINT64 SplashBase, UINT32 X0, UINT32 Y0, UINT32 Width,
                          UINT32 Height, UINT32 Color) {
    UINT32 X;
    UINT32 Y;

    for (Y = Y0; Y < Y0 + Height && Y < BOARD_FRAMEBUFFER_HEIGHT; Y++) {
        for (X = X0; X < X0 + Width && X < BOARD_FRAMEBUFFER_WIDTH; X++) {
            *PixelAt(SplashBase, X, Y) = Color;
        }
    }
}

static void DrawGlyphScaled(UINT64 SplashBase, UINT32 Left, UINT32 Top,
                            char Character, UINT32 Color, UINT32 Scale) {
    const UINT8 *Rows;
    UINT32 Row;
    UINT32 Column;
    UINT32 ScaleY;
    UINT32 ScaleX;
    UINT32 Index;

    if (Scale == 0) {
        Scale = 1;
    }
    if (Character < 0x20 || Character > 0x7E) {
        Character = '?';
    }
    Index = (UINT32)(UINT8)Character - 0x20u;
    Rows = sGlyphBitmap[Index];
    for (Row = 0; Row < GLYPH_HEIGHT; Row++) {
        for (ScaleY = 0; ScaleY < Scale; ScaleY++) {
            for (Column = 0; Column < GLYPH_WIDTH; Column++) {
                if ((Rows[Row] & (0x80u >> Column)) == 0) {
                    continue;
                }
                for (ScaleX = 0; ScaleX < Scale; ScaleX++) {
                    UINT32 X = Left + Column * Scale + ScaleX;
                    UINT32 Y = Top + Row * Scale + ScaleY;
                    if (X < BOARD_FRAMEBUFFER_WIDTH && Y < BOARD_FRAMEBUFFER_HEIGHT) {
                        *PixelAt(SplashBase, X, Y) = Color;
                    }
                }
            }
        }
    }
}

static void DrawStringScaled(UINT64 SplashBase, UINT32 Left, UINT32 Top,
                             const char *Text, UINT32 Color, UINT32 Scale) {
    UINT32 X = Left;
    const char *Cursor;

    for (Cursor = Text; Cursor != 0 && *Cursor != '\0'; Cursor++) {
        DrawGlyphScaled(SplashBase, X, Top, *Cursor, Color, Scale);
        X += GLYPH_WIDTH * Scale + Scale;
    }
}

static void ClearSplashBuffer(UINT64 PhysicalBase) {
    volatile UINT32 *Pixels = (volatile UINT32 *)(UINTN)PhysicalBase;
    UINTN WordCount;
    UINTN Index;

    WordCount = ((UINTN)BOARD_FRAMEBUFFER_HEIGHT *
                 (UINTN)BOARD_FRAMEBUFFER_STRIDE_BYTES) /
                sizeof(UINT32);
    for (Index = 0; Index < WordCount; Index++) {
        Pixels[Index] = COLOR_TEXT_BACK;
    }
}

/*
 * 整帧清黑：按 stride 线性写。主缓冲 0x9D600000（去 MIX/Android logo）。
 * 顶栏锁标：aboot 平面，主缓冲 Y=0 已在锁下方；另清 ALT 试是否同层残影。
 * 不在 ALT 上画彩条/字（双扫会花屏）。
 */
int BoardBringUpSplashClear(void) {
    ClearSplashBuffer(BOARD_SPLASH_PHYSICAL_BASE);
#if defined(BOARD_SPLASH_PHYSICAL_BASE_ALT)
    ClearSplashBuffer(BOARD_SPLASH_PHYSICAL_BASE_ALT);
#endif
    return 0;
}

static void PaintChrome(UINT64 SplashBase, const char *Text) {
    UINT32 BarHeight = 48u;
    UINT32 Quarter = BOARD_FRAMEBUFFER_WIDTH / 4u;

    /* 左→右：红 | 绿 | 蓝 | 白（各 270px） */
    FillRectangle(SplashBase, 0, 0, Quarter, BarHeight, COLOR_BAR_RED);
    FillRectangle(SplashBase, Quarter, 0, Quarter, BarHeight, COLOR_BAR_GREEN);
    FillRectangle(SplashBase, Quarter * 2u, 0, Quarter, BarHeight, COLOR_BAR_BLUE);
    FillRectangle(SplashBase, Quarter * 3u, 0, Quarter, BarHeight, COLOR_BAR_WHITE);
    DrawStringScaled(SplashBase, Quarter / 2u - 8u, 12u, "R", COLOR_TEXT_BACK, 2u);
    DrawStringScaled(SplashBase, Quarter + Quarter / 2u - 8u, 12u, "G", COLOR_TEXT_BACK, 2u);
    DrawStringScaled(SplashBase, Quarter * 2u + Quarter / 2u - 8u, 12u, "B",
                     COLOR_TEXT_BACK, 2u);
    DrawStringScaled(SplashBase, Quarter * 3u + Quarter / 2u - 8u, 12u, "W",
                     COLOR_TEXT_BACK, 2u);

    /* 标题在彩条下方黑底上（不在红格里面）——这是刻意排版，不是错位 */
    DrawStringScaled(SplashBase, 32, BarHeight + 24u, Text, COLOR_TEXT, TEXT_SCALE);
}

int BoardBringUpSplashPaint(const char *Text) {
    if (Text == 0) {
        Text = "Blocks ready";
    }

    /* 只画 aboot cont_splash @0x9D600000；勿再画 0x9D400000（与前者重叠会出双条/花屏） */
    (void)BoardBringUpSplashClear();
    PaintChrome(BOARD_SPLASH_PHYSICAL_BASE, Text);
    return 0;
}

/*
 * 状态行：与标题同级 scale=4（真机可读）；调用方须按 ~48px 行距排 Y。
 */
int BoardBringUpSplashPaintLine(UINT32 Top, const char *Text) {
    UINT64 SplashBase = BOARD_SPLASH_PHYSICAL_BASE;
    UINT32 Scale = TEXT_SCALE;
    UINT32 LineHeight;

    if (Text == 0) {
        return -1;
    }
    /* 行高留余量，避免 scale4 与邻行/旧字叠影 */
    LineHeight = GLYPH_HEIGHT * Scale + 24u;
    FillRectangle(SplashBase, 0, Top, BOARD_FRAMEBUFFER_WIDTH, LineHeight,
                  COLOR_TEXT_BACK);
    DrawStringScaled(SplashBase, 24, Top + 4u, Text, COLOR_TEXT, Scale);
    return 0;
}

