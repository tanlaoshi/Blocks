static volatile UINT32 *PixelAt(UINT64 SplashBase, UINT32 X, UINT32 Y) {
    UINT8 *Base = (UINT8 *)(UINTN)SplashBase;
    return (volatile UINT32 *)(Base + (UINTN)Y * BOARD_FRAMEBUFFER_STRIDE_BYTES +
                               (UINTN)X * 4u);
}

static void FillRectangle(UINT64 SplashBase, UINT32 X0, UINT32 Y0, UINT32 Width,
                          UINT32 Height, UINT32 Color) {
    UINT32 X;
    UINT32 Y;

    for (Y = Y0; Y < Y0 + Height && Y < BOARD_FRAMEBUFFER_HEIGHT; Y++) {
        for (X = X0; X < X0 + Width && X < BOARD_FRAMEBUFFER_WIDTH; X++) {
            *PixelAt(SplashBase, X, Y) = Color;
        }
    }
}

static void DrawGlyphScaled(UINT64 SplashBase, UINT32 Left, UINT32 Top,
                            char Character, UINT32 Color, UINT32 Scale) {
    const UINT8 *Rows;
    UINT32 Row;
    UINT32 Column;
    UINT32 ScaleY;
    UINT32 ScaleX;
    UINT32 Index;

    if (Scale == 0) {
        Scale = 1;
    }
    if (Character < 0x20 || Character > 0x7E) {
        Character = '?';
    }
    Index = (UINT32)(UINT8)Character - 0x20u;
    Rows = sGlyphBitmap[Index];
    for (Row = 0; Row < GLYPH_HEIGHT; Row++) {
        for (ScaleY = 0; ScaleY < Scale; ScaleY++) {
            for (Column = 0; Column < GLYPH_WIDTH; Column++) {
                if ((Rows[Row] & (0x80u >> Column)) == 0) {
                    continue;
                }
                for (ScaleX = 0; ScaleX < Scale; ScaleX++) {
                    UINT32 X = Left + Column * Scale + ScaleX;
                    UINT32 Y = Top + Row * Scale + ScaleY;
                    if (X < BOARD_FRAMEBUFFER_WIDTH && Y < BOARD_FRAMEBUFFER_HEIGHT) {
                        *PixelAt(SplashBase, X, Y) = Color;
                    }
                }
            }
        }
    }
}

static void DrawStringScaled(UINT64 SplashBase, UINT32 Left, UINT32 Top,
                             const char *Text, UINT32 Color, UINT32 Scale) {
    UINT32 X = Left;
    const char *Cursor;

    for (Cursor = Text; Cursor != 0 && *Cursor != '\0'; Cursor++) {
        DrawGlyphScaled(SplashBase, X, Top, *Cursor, Color, Scale);
        X += GLYPH_WIDTH * Scale + Scale;
    }
}

static void PaintOne(UINT64 SplashBase, const char *Text) {
    UINT32 BarHeight = 48u;

    FillRectangle(SplashBase, 0, 0, BOARD_FRAMEBUFFER_WIDTH / 4u, BarHeight,
                  COLOR_BAR_RED);
    FillRectangle(SplashBase, BOARD_FRAMEBUFFER_WIDTH / 4u, 0,
                  BOARD_FRAMEBUFFER_WIDTH / 4u, BarHeight, COLOR_BAR_GREEN);
    FillRectangle(SplashBase, BOARD_FRAMEBUFFER_WIDTH / 2u, 0,
                  BOARD_FRAMEBUFFER_WIDTH / 4u, BarHeight, COLOR_BAR_BLUE);
    FillRectangle(SplashBase, (BOARD_FRAMEBUFFER_WIDTH * 3u) / 4u, 0,
                  BOARD_FRAMEBUFFER_WIDTH - (BOARD_FRAMEBUFFER_WIDTH * 3u) / 4u,
                  BarHeight, COLOR_BAR_WHITE);

    FillRectangle(SplashBase, 16, BarHeight + 16u, BOARD_FRAMEBUFFER_WIDTH - 32u,
                  GLYPH_HEIGHT * TEXT_SCALE + 24u, COLOR_TEXT_BACK);
    DrawStringScaled(SplashBase, 32, BarHeight + 24u, Text, COLOR_TEXT, TEXT_SCALE);
}

int BoardBringUpSplashPaint(const char *Text) {
    if (Text == 0) {
        Text = "Blocks ready";
    }

    /* 只画 aboot cont_splash @0x9D600000；勿再画 0x9D400000（与前者重叠会出双条/花屏） */
    PaintOne(BOARD_SPLASH_PHYSICAL_BASE, Text);
    return 0;
}

/*
 * 状态行：小字（scale=2）贴在彩条标题正下方，避免大字裁切 / 出 logo 可视带。
 */
int BoardBringUpSplashPaintLine(UINT32 Top, const char *Text) {
    UINT64 SplashBase = BOARD_SPLASH_PHYSICAL_BASE;
    UINT32 Scale = 2u;
    UINT32 LineHeight;

    if (Text == 0) {
        return -1;
    }
    LineHeight = GLYPH_HEIGHT * Scale + 12u;
    FillRectangle(SplashBase, 16, Top, BOARD_FRAMEBUFFER_WIDTH - 32u, LineHeight,
                  COLOR_TEXT_BACK);
    DrawStringScaled(SplashBase, 24, Top + 4u, Text, COLOR_TEXT, Scale);
    return 0;
}

