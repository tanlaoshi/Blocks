static const UINT8 gWifiAesRcon[WIFI_AES_RCON_LENGTH] = {
    0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
};

static UINT8 Xtime(UINT8 X)
{
    return (UINT8)((X << 1) ^ ((X & 0x80u) ? WIFI_AES_GF_POLYNOMIAL : 0u));
}

static UINT8 GfMultiply(UINT8 A, UINT8 B)
{
    UINT8 Product = 0;
    UINTN I;

    for (I = 0; I < WIFI_AES_GF_MULTIPLY_BITS; I++) {
        if (B & 1u) {
            Product = (UINT8)(Product ^ A);
        }
        A = Xtime(A);
        B = (UINT8)(B >> 1);
    }
    return Product;
}

static void SubBytes(UINT8 State[WIFI_AES_BLOCK_LENGTH])
{
    UINTN I;
    for (I = 0; I < WIFI_AES_BLOCK_LENGTH; I++) {
        State[I] = gWifiAesSbox[State[I]];
    }
}

static void InvSubBytes(UINT8 State[WIFI_AES_BLOCK_LENGTH])
{
    UINTN I;
    for (I = 0; I < WIFI_AES_BLOCK_LENGTH; I++) {
        State[I] = gWifiAesInvSbox[State[I]];
    }
}

static void ShiftRows(UINT8 State[WIFI_AES_BLOCK_LENGTH])
{
    UINT8 Temporary;
    Temporary = State[1];  State[1] = State[5];  State[5] = State[9];
    State[9] = State[13];  State[13] = Temporary;
    Temporary = State[2];  State[2] = State[10]; State[10] = Temporary;
    Temporary = State[6];  State[6] = State[14]; State[14] = Temporary;
    Temporary = State[15]; State[15] = State[11]; State[11] = State[7];
    State[7] = State[3];   State[3] = Temporary;
}

static void InvShiftRows(UINT8 State[WIFI_AES_BLOCK_LENGTH])
{
    UINT8 Temporary;
    Temporary = State[13]; State[13] = State[9]; State[9] = State[5];
    State[5] = State[1];   State[1] = Temporary;
    Temporary = State[2];  State[2] = State[10]; State[10] = Temporary;
    Temporary = State[6];  State[6] = State[14]; State[14] = Temporary;
    Temporary = State[3];  State[3] = State[7];  State[7] = State[11];
    State[11] = State[15]; State[15] = Temporary;
}

static void MixColumns(UINT8 State[WIFI_AES_BLOCK_LENGTH])
{
    UINTN C;
    for (C = 0; C < WIFI_AES_COLUMN_COUNT; C++) {
        UINT8 *Column = &State[C * WIFI_AES_WORD_LENGTH];
        UINT8 A0 = Column[0], A1 = Column[1], A2 = Column[2], A3 = Column[3];
        UINT8 X = (UINT8)(A0 ^ A1 ^ A2 ^ A3);
        Column[0] = (UINT8)(A0 ^ Xtime((UINT8)(A0 ^ A1)) ^ X);
        Column[1] = (UINT8)(A1 ^ Xtime((UINT8)(A1 ^ A2)) ^ X);
        Column[2] = (UINT8)(A2 ^ Xtime((UINT8)(A2 ^ A3)) ^ X);
        Column[3] = (UINT8)(A3 ^ Xtime((UINT8)(A3 ^ A0)) ^ X);
    }
}

static void InvMixColumns(UINT8 State[WIFI_AES_BLOCK_LENGTH])
{
    UINTN C;
    for (C = 0; C < WIFI_AES_COLUMN_COUNT; C++) {
        UINT8 *Column = &State[C * WIFI_AES_WORD_LENGTH];
        UINT8 A0 = Column[0], A1 = Column[1], A2 = Column[2], A3 = Column[3];
        Column[0] = (UINT8)(GfMultiply(A0, 0x0eu) ^ GfMultiply(A1, 0x0bu)
                          ^ GfMultiply(A2, 0x0du) ^ GfMultiply(A3, 0x09u));
        Column[1] = (UINT8)(GfMultiply(A0, 0x09u) ^ GfMultiply(A1, 0x0eu)
                          ^ GfMultiply(A2, 0x0bu) ^ GfMultiply(A3, 0x0du));
        Column[2] = (UINT8)(GfMultiply(A0, 0x0du) ^ GfMultiply(A1, 0x09u)
                          ^ GfMultiply(A2, 0x0eu) ^ GfMultiply(A3, 0x0bu));
        Column[3] = (UINT8)(GfMultiply(A0, 0x0bu) ^ GfMultiply(A1, 0x0du)
                          ^ GfMultiply(A2, 0x09u) ^ GfMultiply(A3, 0x0eu));
    }
}

static void AddRoundKey(UINT8 State[WIFI_AES_BLOCK_LENGTH], const UINT8 *RoundKey)
{
    UINTN I;
    for (I = 0; I < WIFI_AES_BLOCK_LENGTH; I++) {
        State[I] ^= RoundKey[I];
    }
}

static void KeyExpand(const UINT8 Key[WIFI_AES_KEY_LENGTH],
                      UINT8 RoundKey[WIFI_AES_ROUND_KEY_LENGTH])
{
    UINTN I;
    UINT8 Temporary[WIFI_AES_WORD_LENGTH];
    UINTN RconIndex = 1;

    for (I = 0; I < WIFI_AES_KEY_LENGTH; I++) {
        RoundKey[I] = Key[I];
    }
    for (I = WIFI_AES_KEY_LENGTH; I < WIFI_AES_ROUND_KEY_LENGTH;
         I += WIFI_AES_WORD_LENGTH) {
        Temporary[0] = RoundKey[I - 4];
        Temporary[1] = RoundKey[I - 3];
        Temporary[2] = RoundKey[I - 2];
        Temporary[3] = RoundKey[I - 1];
        if ((I & (WIFI_AES_BLOCK_LENGTH - 1u)) == 0) {
            UINT8 First = Temporary[0];
            Temporary[0] = (UINT8)(gWifiAesSbox[Temporary[1]] ^ gWifiAesRcon[RconIndex++]);
            Temporary[1] = gWifiAesSbox[Temporary[2]];
            Temporary[2] = gWifiAesSbox[Temporary[3]];
            Temporary[3] = gWifiAesSbox[First];
        }
        RoundKey[I]     = (UINT8)(RoundKey[I - WIFI_AES_BLOCK_LENGTH] ^ Temporary[0]);
        RoundKey[I + 1] = (UINT8)(RoundKey[I - WIFI_AES_BLOCK_LENGTH + 1] ^ Temporary[1]);
        RoundKey[I + 2] = (UINT8)(RoundKey[I - WIFI_AES_BLOCK_LENGTH + 2] ^ Temporary[2]);
        RoundKey[I + 3] = (UINT8)(RoundKey[I - WIFI_AES_BLOCK_LENGTH + 3] ^ Temporary[3]);
    }
}

int WifiAesEncrypt(const UINT8 Key[WIFI_AES_KEY_LENGTH],
                   const UINT8 Input[WIFI_AES_BLOCK_LENGTH],
                   UINT8 Output[WIFI_AES_BLOCK_LENGTH])
{
    UINT8 RoundKey[WIFI_AES_ROUND_KEY_LENGTH];
    UINT8 State[WIFI_AES_BLOCK_LENGTH];
    UINTN Round;
    UINTN I;

    if (Key == NULL || Input == NULL || Output == NULL) {
        return 0;
    }
    KeyExpand(Key, RoundKey);
    for (I = 0; I < WIFI_AES_BLOCK_LENGTH; I++) {
        State[I] = Input[I];
    }
    AddRoundKey(State, RoundKey);
    for (Round = 1; Round < WIFI_AES_ROUNDS; Round++) {
        SubBytes(State);
        ShiftRows(State);
        MixColumns(State);
        AddRoundKey(State, &RoundKey[Round * WIFI_AES_BLOCK_LENGTH]);
    }
    SubBytes(State);
    ShiftRows(State);
    AddRoundKey(State, &RoundKey[WIFI_AES_ROUNDS * WIFI_AES_BLOCK_LENGTH]);
    for (I = 0; I < WIFI_AES_BLOCK_LENGTH; I++) {
        Output[I] = State[I];
    }
    return 1;
}

int WifiAesDecrypt(const UINT8 Key[WIFI_AES_KEY_LENGTH],
                   const UINT8 Input[WIFI_AES_BLOCK_LENGTH],
                   UINT8 Output[WIFI_AES_BLOCK_LENGTH])
{
    UINT8 RoundKey[WIFI_AES_ROUND_KEY_LENGTH];
    UINT8 State[WIFI_AES_BLOCK_LENGTH];
    int Round;
    UINTN I;

    if (Key == NULL || Input == NULL || Output == NULL) {
        return 0;
    }
    KeyExpand(Key, RoundKey);
    for (I = 0; I < WIFI_AES_BLOCK_LENGTH; I++) {
        State[I] = Input[I];
    }
    AddRoundKey(State, &RoundKey[WIFI_AES_ROUNDS * WIFI_AES_BLOCK_LENGTH]);
    InvShiftRows(State);
    InvSubBytes(State);
    for (Round = (int)WIFI_AES_ROUNDS - 1; Round >= 1; Round--) {
        AddRoundKey(State, &RoundKey[(UINTN)Round * WIFI_AES_BLOCK_LENGTH]);
        InvMixColumns(State);
        InvShiftRows(State);
        InvSubBytes(State);
    }
    AddRoundKey(State, RoundKey);
    for (I = 0; I < WIFI_AES_BLOCK_LENGTH; I++) {
        Output[I] = State[I];
    }
    return 1;
}
